INSERT INTO HistoricPriceEMALast ( ISIN, UltimoDiDate, UltimoDiClose, S20, S50, S100, S200, E20, E50, E100, E200 )
SELECT TEMA.ISIN, TEMA.Date AS UltimoDiDate, TEMA.Close AS UltimoDiClose, TEMA.SMA20 AS S20, TEMA.SMA50 AS S50, TEMA.SMA100 AS S100, TEMA.SMA200 AS S200, TEMA.EMA20 AS E20, TEMA.EMA50 AS E50, TEMA.EMA100 AS E100, TEMA.EMA200 AS E200
FROM HistoricPriceEMA AS TEMA
WHERE (((TEMA.Date)=Date()))
ORDER BY TEMA.ISIN;
